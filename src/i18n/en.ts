/**
 * Widens literal string types while preserving the key structure.
 *
 * `as const` above gives callers precise autocompletion, but a locale must be
 * allowed to hold DIFFERENT strings with the SAME keys. Without this, `vi: Dict`
 * would require the Vietnamese text to equal the English text.
 * Missing or extra keys still fail the build — which is the point.
 */
type Widen<T> = T extends string ? string
  : T extends readonly unknown[] ? { [K in keyof T]: Widen<T[K]> }
  : T extends object ? { [K in keyof T]: Widen<T[K]> }
  : T;

export type Dict = Widen<typeof en>;

